# PlatformIO pre-script. Writes src/build_version.h from git and the clock
# so the web UI can show which firmware image is running.

Import("env")

import datetime
import os
import subprocess

project_dir = env["PROJECT_DIR"]
header_path = os.path.join(project_dir, "src", "build_version.h")


def git_output(args):
    try:
        return subprocess.check_output(
            args, cwd=project_dir, stderr=subprocess.DEVNULL
        ).decode().strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


revision = git_output(["git", "rev-parse", "--short=7", "HEAD"]) or "unknown"
# Ignore untracked files. The generated header and the build tree would
# otherwise mark every image dirty.
if git_output(["git", "status", "--porcelain", "--untracked-files=no"]):
    revision += "-dirty"

built = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")

contents = (
    "#pragma once\n"
    "// Generated by scripts/build_version.py. Do not edit.\n"
    '#define BUILD_GIT_HASH "%s"\n'
    '#define BUILD_DATE "%s"\n' % (revision, built)
)

previous = ""
if os.path.exists(header_path):
    with open(header_path, "r") as handle:
        previous = handle.read()

if previous != contents:
    with open(header_path, "w") as handle:
        handle.write(contents)
